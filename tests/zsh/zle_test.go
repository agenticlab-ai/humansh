	asset := assetPath(t)
	repo := filepath.Clean(filepath.Join(filepath.Dir(asset), "..", "..", ".."))
	temp := t.TempDir()
	fake := filepath.Join(temp, "humansh")
	build := exec.Command("go", "build", "-o", fake, filepath.Join(repo, "tests", "zsh", "testdata", "fakehumansh.go"))
	build.Dir = repo
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build fake backend: %v\n%s", err, output)
	}
	calls := filepath.Join(temp, "calls.log")
