// TestSourcingTheAssetSpawnsNoSubprocess pins the shell-startup cost of the
// integration at zero processes. Resolving anything by running humansh while
// .zshrc is being sourced puts an untimed blocking subprocess in front of every
// interactive shell, so a stalled home directory would hang every new terminal.
// Values the integration needs at load time come from the managed block instead.
//
// The probe below stands in for humansh rather than the shared fake backend: it
// records every invocation before doing anything else and never reads stdin, so
// it cannot miss a call or block on a terminal the way a stdin-reading fake can.
func TestSourcingTheAssetSpawnsNoSubprocess(t *testing.T) {
	asset := assetPath(t)
	temp := t.TempDir()
	calls := filepath.Join(temp, "calls.log")
	probe := "#!/bin/sh\nprintf '%s\\n' \"$*\" >> " + calls + "\nexit 0\n"
	if err := os.WriteFile(filepath.Join(temp, "humansh"), []byte(probe), 0o700); err != nil {
		t.Fatal(err)
	}
	script := `zmodload zsh/zpty || exit 90
zpty -b H env PATH="$HUMANSH_FAKE_DIR:$PATH" HUMANSH_PROVIDER_LABEL=Codex HUMANSH_ASSET="$HUMANSH_ASSET" zsh -f
wait_for() {
  local pattern=$1 chunk seen=''
  local -i attempt
  for (( attempt = 1; attempt <= 500; attempt++ )); do
    while zpty -r -t H chunk; do seen+=$chunk; done
    [[ $seen == ${~pattern} ]] && { print -r -- "$seen"; return 0; }
    sleep 0.02
  done
  print -ru2 -- "missing $pattern; received ${(V)seen}"
  return 1
}
zpty -w H 'PS1="Q> "; source "$HUMANSH_ASSET"; print -r -- SOURCED'
wait_for '*SOURCED*Q> *' || exit 91
print -r -- QUIET_DONE
zpty -d H`
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "zsh", "-f", "-c", script)
	cmd.Dir = temp
	cmd.Env = append(os.Environ(), "HUMANSH_ASSET="+asset, "HUMANSH_FAKE_DIR="+temp)
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("quiet-startup scenario: %v\n%s", err, output)
	}
	if !strings.Contains(string(output), "SOURCED") {
		t.Fatalf("asset did not finish sourcing:\n%s", output)
	}
	if data, readErr := os.ReadFile(calls); readErr == nil && len(strings.TrimSpace(string(data))) != 0 {
		t.Fatalf("sourcing the asset invoked humansh; it must stay process-free at startup. Invocations:\n%s", data)
	}
}
